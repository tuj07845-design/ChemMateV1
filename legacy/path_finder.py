import os


# ============================================================
# ChemMate V1
# path_finder
# ============================================================
#
# 功能：
#
#     Agent 提供 Aspen 文件名
#             ↓
#     path_finder 在电脑中搜索
#             ↓
#     找到对应 .bkp 文件
#             ↓
#     返回完整绝对路径
#
# ============================================================


def find_aspen_file(filename):
    """
    根据文件名寻找 Aspen Plus 模型。

    参数：
        filename
        例如：
            10万吨环己烷.bkp

    返回：
        找到：
            完整文件路径

        找不到：
            None
    """


    # ========================================================
    # 1. 获取当前用户目录
    # ========================================================

    user = os.path.expanduser("~")


    print("开始寻找 Aspen 文件...")
    print("文件名：", filename)


    # ========================================================
    # 2. 定义搜索范围
    # ========================================================
    #
    # 这里先搜索用户目录。
    #
    # 例如：
    #
    # C:\Users\Fool
    #
    # 下面所有文件夹都会被搜索。
    #
    # ========================================================

    search_root = user


    print("搜索范围：")
    print(search_root)


    # ========================================================
    # 3. 开始递归搜索
    # ========================================================

    for root, dirs, files in os.walk(search_root):


        # ====================================================
        # 4. 检查当前文件夹中的文件
        # ====================================================

        for file in files:


            # ------------------------------------------------
            # 文件名完全匹配
            # ------------------------------------------------

            if file.lower() == filename.lower():


                # --------------------------------------------
                # 找到文件
                # --------------------------------------------

                full_path = os.path.join(
                    root,
                    file
                )


                # 转换成绝对路径

                full_path = os.path.abspath(
                    full_path
                )


                print("\n========================================")
                print("✅ 找到 Aspen 文件")
                print("========================================")

                print("文件名：")
                print(file)

                print("\n完整路径：")
                print(full_path)


                # 返回路径

                return full_path


    # ========================================================
    # 5. 没有找到
    # ========================================================

    print("\n========================================")
    print("❌ 没有找到 Aspen 文件")
    print("========================================")

    print("搜索文件：")
    print(filename)


    return None


# ============================================================
# 测试
# ============================================================

if __name__ == "__main__":


    print("========================================")
    print("     ChemMate V1 - Path Finder")
    print("========================================")


    # ========================================================
    # 模拟 Agent 提供的文件名
    # ========================================================

    filename = "换热单元.apwz"


    # ========================================================
    # 调用 Path Finder
    # ========================================================

    file_path = find_aspen_file(
        filename
    )


    # ========================================================
    # 最终结果
    # ========================================================

    print("\n========================================")
    print("最终返回结果")
    print("========================================")


    if file_path:

        print("success = True")

        print(
            "file_path =",
            file_path
        )

    else:

        print("success = False")